export type CreatorMessage = keyof typeof creatorTranslations
const order = ['zh', 'ja', 'ko', 'es', 'de', 'fr', 'id'] as const
export function creatorCopy(
  locale: Locale,
  key: CreatorMessage,
  values: Record<string, string | number> = {},
) {
  const text =
    locale === 'en'
      ? key
      : creatorTranslations[key][
          order.indexOf(locale as (typeof order)[number])
        ]
  return text.replace(/\{(\w+)\}/g, (token, name) =>
    values[name] === undefined ? token : String(values[name]),
  )
}

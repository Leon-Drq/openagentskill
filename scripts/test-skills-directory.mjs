import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { register } from 'node:module'
await import('./test-trending.mjs')
register('./test-owner-publication-loader.mjs', import.meta.url)
const { directoryCategories, directoryCategoryOptions, matchesDirectoryCategory, directoryHref, sortDirectoryCandidates, isDirectorySnapshot } = await import('../lib/skills/directory.ts')
const { directoryCopy, directoryLabel } = await import('../lib/i18n/directory-copy.ts')
assert.deepEqual(directoryCategories('[chemistry, drug-discovery]'), ['chemistry','drug-discovery'])
assert.deepEqual(directoryCategoryOptions(['Coding Agents','coding-agents','Finance','finance-quant','[chemistry]']), ['chemistry','coding-agents','finance'])
assert.ok(matchesDirectoryCategory('Design','design-creative'))
assert.ok(matchesDirectoryCategory('Research','rag-knowledge'))
assert.ok(!matchesDirectoryCategory('finance','research'))
assert.equal(directoryHref('/ja/skills','lang=ja&q=hello&page=4',{ category: 'design-creative' }), '/ja/skills?lang=ja&q=hello&category=design-creative')
assert.equal(directoryHref('/skills','lang=zh&q=ppt&sort=stars',{ page: '2' }), '/skills?lang=zh&q=ppt&sort=stars&page=2')
assert.equal(directoryHref('/skills','q=a&page=2',{ q: undefined }), '/skills')
const item=(slug, stars)=>({record:{slug,github_stars:stars,quality_score:80,created_at:'2026-01-01',updated_at:'2026-01-02'}})
assert.deepEqual(sortDirectoryCandidates([item('a',3),item('b',20),item('c',10)],'stars').map(v=>v.record.slug), ['b','c','a'])
assert.ok(isDirectorySnapshot({id:'fallback-ppt'}))
assert.ok(isDirectorySnapshot({id:'snapshot-ppt'}))
assert.ok(!isDirectorySnapshot({id:'real-uuid'}))
for (const locale of ['en','zh','ja','ko','es','de','fr','id']) {
  const copy=directoryCopy(locale)
  assert.deepEqual(Object.keys(copy),Object.keys(directoryCopy('en')))
  assert.ok(Object.values(copy).every(v=>v.trim()&&!v.includes('\uFFFD')))
  assert.ok(directoryLabel(locale,'video-creation'))
}
const source=readFileSync('components/skills-page-client.tsx','utf8')
assert.equal((source.match(/<form\b/g)||[]).length,1)
assert.equal((source.match(/<h1\b/g)||[]).length,1)
assert.ok(source.indexOf('data-directory-results')<source.indexOf('id="directory-collections"'))
assert.match(source, /<details[^>]+data-directory-filters/)
assert.match(source, /<Link[^>]+rel="next"[^>]+href=/)
assert.match(source, /<GitHubOwnerAvatar/)
assert.match(source, /skill\.snapshot \? c\.snapshot/)
assert.doesNotMatch(source, /<InstallCommand|skill\.verified &&|Supply tracks|Decision filters/)
const server=readFileSync('app/skills/page.tsx','utf8')
assert.match(server, /matchesDirectoryCategory\(record.category, category\)/)
assert.match(server, /sortDirectoryCandidates\(filteredRecords, sort\)/)
assert.match(server, /index: isCanonicalEnglishDirectory/, 'Index policy remains unchanged in this visual release')
assert.match(server, /buildSkillsPageJsonLd\(skills, query \? \[\] : directorySections, locale\)/, 'Schema includes only visible sections')
const localized=readFileSync('app/[locale]/[page]/page.tsx','utf8')
assert.match(localized, /route.page === 'skills'[\s\S]*<SkillsPage searchParams=/, 'Localized routes use the same directory')
assert.match(localized, /\.\.\.resolvedSearchParams, lang: route.locale/, 'Preserve every localized filter and pagination parameter')
console.log('Skills directory: category aliases, stable links, sorting, snapshot labels, eight locales and compact layout contracts passed.')

import assert from 'node:assert/strict'
import { register } from 'node:module'
import { readFileSync } from 'node:fs'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
register('./test-owner-publication-loader.mjs', import.meta.url)
const { prepareSkillDocument, resolveSkillDocumentUrl, quoteSourceWrappers } = await import('../lib/skills/document.ts')
const { SkillDocumentBody } = await import('../components/skill-document-body.tsx')
const { documentCopy, documentCopyKeys } = await import('../lib/i18n/skill-document-copy.ts')
const sourceUrl = 'https://github.com/owner/repo/blob/abc123/skills/demo/SKILL.md'
const render = body => renderToStaticMarkup(createElement(SkillDocumentBody, { body, sourceUrl }))
const prepared = prepareSkillDocument('\uFEFF---\r\nname: example\r\ndescription: |\r\n  More text\r\n---\r\n\r\n# Title\r\n\r\nBody')
assert.equal(prepared.body, '# Title\n\nBody')
assert.match(prepared.metadata, /name: example/)
for (const source of ['---\nordinary text\n---\nBody', '---\nname: unfinished', 'Body\n---\nname: not metadata']) assert.equal(prepareSkillDocument(source).body, source)
assert.equal(prepareSkillDocument('text '.repeat(1000)).isLong, true)
assert.equal(prepareSkillDocument('Short prose.').isLong, false)
const html = render('# Main\n\n**Strong** and `code`\n\n## Steps\n\n1. One\n2. Two\n\n- Parent\n  - Nested\n\n| Name | Value |\n|---|---|\n| A | B |\n\n```js\nconst x = "<script>";\n```\n\n[Steps](#steps)\n\n[Guide](../guide.md)\n\n![Example](./output.svg)')
for (const tag of ['h3', 'h4', 'strong', 'code', 'ol', 'ul', 'li', 'table', 'th', 'td', 'pre']) assert.match(html, new RegExp(`<${tag}\\b`), tag)
assert.doesNotMatch(html, /<h[12]\b|<img\b/)
assert.match(html, /id="skill-doc-steps"/)
assert.match(html, /href="#skill-doc-steps"/)
assert.match(html, /href="https:\/\/github.com\/owner\/repo\/blob\/abc123\/skills\/guide.md"/)
assert.match(html, /rel="nofollow ugc noopener noreferrer"/)
assert.match(html, /tabindex="0"/)
const custom = render('<SUBAGENT-STOP>\nSource note.\n</SUBAGENT-STOP>\n\n<EXTREMELY-IMPORTANT>\nPreserved instructions.\n</EXTREMELY-IMPORTANT>\n\n## Rule\n\nReadable **content**.')
assert.match(custom, /Source note/)
assert.match(custom, /Preserved instructions/)
assert.match(custom, /<strong>content<\/strong>/)
assert.doesNotMatch(custom, /subagent-stop|extremely-important/i)
assert.equal((custom.match(/<blockquote>/g) || []).length, 2)
const multiParagraph = render('<SOURCE-NOTE>\nFirst.\n\nSecond.\nClosing paragraph.\n</SOURCE-NOTE>\n\n## Outside\n\nNot quoted.')
assert.match(multiParagraph, /<\/blockquote>\s*<h3[^>]*>Outside/)
assert.match(multiParagraph, /<p>Second\.\nClosing paragraph\.<\/p>/)
const fenced = '```xml\n<SOURCE-NOTE>\nExample\n</SOURCE-NOTE>\n```'
assert.equal(quoteSourceWrappers(fenced), fenced)
assert.equal(quoteSourceWrappers('<SOURCE-NOTE>\nUnclosed\n\n## Heading'), '`<SOURCE-NOTE>`\nUnclosed\n\n## Heading')
const malicious = render('<script>alert(1)</script>\n\n<style>body{display:none}</style>\n\n<iframe src="https://evil.example"></iframe>\n\n<img src="https://evil.example/pixel" onerror="alert(2)">\n\n<a href="javascript:alert(3)" onclick="alert(4)">Bad</a>\n\n<div id="install-options" style="position:fixed" onmouseover="alert(5)">Visible</div>\n\n[Bad data](data:text/html,evil)\n\n<svg onload="alert(6)"><script>alert(7)</script></svg>')
assert.doesNotMatch(malicious, /<(script|style|iframe|img|svg)\b|\son\w+=|\sstyle=|href="(?:javascript|data):|id="install-options"/i)
assert.match(malicious, /Visible/)
for (const value of ['javascript:alert(1)', 'data:image/svg+xml,x', 'vbscript:x', 'https://user:pass@example.com', 'java\nscript:x', '\\evil.test']) assert.equal(resolveSkillDocumentUrl(value, sourceUrl), undefined, value)
assert.equal(resolveSkillDocumentUrl('../guide.md', sourceUrl), 'https://github.com/owner/repo/blob/abc123/skills/guide.md')
assert.equal(resolveSkillDocumentUrl('/docs/test.md', sourceUrl), 'https://github.com/owner/repo/blob/abc123/docs/test.md')
assert.equal(resolveSkillDocumentUrl('mailto:author@example.com', sourceUrl), 'mailto:author@example.com')
assert.equal(resolveSkillDocumentUrl('https://example.com/guide', ''), 'https://example.com/guide')
assert.equal(resolveSkillDocumentUrl('docs/guide.md', 'https://github.com/owner/repo'), 'https://github.com/owner/repo/blob/HEAD/docs/guide.md')
const headings = render('## Same\n\n## Same\n\n[Second](#same-1)')
assert.match(headings, /id="skill-doc-same-1"/)
assert.match(headings, /href="#skill-doc-same-1"/)
const footnote = render('Text[^1]\n\n[^1]: Footnote text.')
assert.match(footnote, /href="#skill-doc-anchor-fn-1"/)
assert.match(footnote, /id="skill-doc-anchor-fn-1"/)
assert.match(footnote, /href="#skill-doc-anchor-fnref-1"/)
for (const [locale, copy] of Object.entries(documentCopy)) {
  assert.equal(copy.length, documentCopyKeys.length, locale)
  assert.ok(copy.every(value => value.trim()), locale)
}
const component = readFileSync(new URL('../components/skill-document.tsx', import.meta.url), 'utf8')
assert.ok(!component.includes("'use client'"), 'Markdown parser stays server-side')
assert.match(component, /\{source\}<\/pre>/, 'original source remains escaped, not executed')
assert.match(component, /data-full-document/)
console.log('Skill document rendering passed: frontmatter, GFM, source wrappers, heading hierarchy, anchors, relative links, XSS, no remote embeds and eight languages.')

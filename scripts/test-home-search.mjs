import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const source = readFileSync('components/home-page-enhanced.tsx', 'utf8')
const messages = readFileSync('lib/i18n/home-search-copy.ts', 'utf8')
const hint = readFileSync('components/animated-search-hint.tsx', 'utf8')
assert.match(hint, /4000/)
assert.match(hint, /prefers-reduced-motion: reduce/)
assert.match(hint, /clearInterval\(timer\)/)
assert.match(hint, /visibilitychange/)
assert.match(hint, /aria-hidden="true"/)
assert.match(hint, /pointer-events-none/)
assert.doesNotMatch(hint, /fetch\(|setTaskQuery/)
assert.match(source, /active=\{!searchFocused && !taskQuery && !isSearching\}/)
assert.equal((source.match(/<input\b/g) || []).length, 1, 'Homepage must have one search input')
assert.ok(source.indexOf('id="hero-task-query"') < source.indexOf('<HomeShowcase />'), 'Search belongs in Hero')
assert.match(source, /role="search"/)
assert.match(source, /htmlFor="hero-task-query"/)
assert.match(source, /event\.preventDefault\(\); void handleFindSkills\(\)/)
assert.match(source, /event\.nativeEvent\.isComposing/)
assert.match(source, /disabled=\{isSearching \|\| !taskQuery\.trim\(\)\}/)
assert.match(source, /prefers-reduced-motion: reduce/)
assert.match(source, /fetch\('\/api\/agent\/resolve'/, 'Preserve existing resolver')
assert.match(source, /getLocalizedNavigationHref\('\/skills', activeLocale\)/)
const connect = readFileSync('components/connect-ai-inline.tsx', 'utf8')
assert.match(source, /<ConnectAiInline locale=\{activeLocale\}/)
assert.match(connect, /getLocalizedNavigationHref\('\/agent\/integration-kit', locale\)/)
assert.match(connect, /await navigator.clipboard.writeText\(CONNECT_AI_PROMPT\)/)
assert.match(connect, /catch \{ setStatus\('error'\) \}/)
assert.match(connect, /ask before changing files or installing anything/)
assert.doesNotMatch(connect, /fetch\(/)
assert.match(source, /<SiteHeader \/>/)
for (const locale of ['en', 'zh', 'ja', 'ko', 'es', 'de', 'fr', 'id']) {
  assert.match(messages, new RegExp(`  ${locale}: \\{ placeholder: .+, browse: .+, connect: .+, indexed: .+ \\}`))
}
console.log('Homepage search checks passed: single Hero form, accessible input, IME, reduced motion, existing resolver, localized links and eight languages.')
